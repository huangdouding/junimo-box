const translations: Record<Locale, TranslationTable> = { zh, en };

function getInitialLocale(): Locale {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "zh" || stored === "en") return stored;
  return "zh";
}

export const locale = ref<Locale>(getInitialLocale());

export function setLocale(l: Locale) {
  locale.value = l;
  localStorage.setItem(STORAGE_KEY, l);
}

export function t(path: string, params?: Record<string, any>): string {
  const parts = path.split(".");
  let dict: any = translations[locale.value];
  for (const part of parts) {
    if (dict == null || typeof dict !== "object") return path;
    dict = dict[part];
  }
  if (dict == null) return path;
  if (typeof dict === "function") return dict(params || {});
  if (typeof dict === "string") return dict;
  return path;
}

// Also expose a raw getter for the current locale's dict (used in report generation)
export function getCurrentDict(): TranslationTable {
  return translations[locale.value];
}

// Reactive locale change trigger for components that need to recompute
export const localeVersion = ref(0);
export function setLocaleAndNotify(l: Locale) {
  setLocale(l);
  localeVersion.value++;
}
